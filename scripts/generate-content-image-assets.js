import fs from 'node:fs'
import path from 'node:path'
import { globby } from 'globby'

const root = process.cwd()
const srcDir = path.resolve(root, 'src')
const contentDir = path.resolve(srcDir, 'content')
const pagesDir = path.resolve(srcDir, 'pages')
const generatedDir = path.resolve(srcDir, 'generated')
const outputFile = path.join(generatedDir, 'contentImageAssets.js')
const imageExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.svg', '.webp'])

const toPosix = (value) => value.replace(/\\/g, '/')

const normalizeModulePath = (value = '') => {
  const segments = []
  toPosix(value)
    .split('/')
    .forEach((segment) => {
      if (!segment || segment === '.') return
      if (segment === '..') {
        if (segments.length && segments[segments.length - 1] !== '..') {
          segments.pop()
          return
        }
      }
      segments.push(segment)
    })
  return segments.join('/')
}

const stripUrlDecorators = (value) => String(value || '').trim()
  .split('#')[0]
  .split('?')[0]

const parseMarkdownImageTarget = (target = '') => {
  const trimmedTarget = String(target || '').trim()
  const parsed = trimmedTarget.match(/^<?([^>\s]+)>?/)
  return parsed?.[1] || ''
}

const resolveReferencedAsset = (markdownFile, target) => {
  const assetPath = parseMarkdownImageTarget(target)
  if (!(assetPath.startsWith('./') || assetPath.startsWith('../'))) return null
  const cleanAssetPath = stripUrlDecorators(assetPath)
  const extension = path.extname(cleanAssetPath).toLowerCase()
  if (!imageExtensions.has(extension)) return null
  return path.resolve(path.dirname(markdownFile), cleanAssetPath)
}

const moduleKeyForAsset = (assetFile) => normalizeModulePath(toPosix(path.relative(pagesDir, assetFile)))

const importPathForAsset = (assetFile) => {
  const relative = toPosix(path.relative(generatedDir, assetFile))
  return relative.startsWith('.') ? relative : `./${relative}`
}

const renderOutput = (entries) => {
  const assetRows = entries.map(({ moduleKey, importPath }) => (
    `  ${JSON.stringify(moduleKey)}: new URL(${JSON.stringify(importPath)}, import.meta.url).href,`
  ))
  return [
    '/* This file is generated by scripts/generate-content-image-assets.js. Do not edit. */',
    'const contentImageAssets = Object.freeze({',
    ...assetRows,
    '})',
    '',
    'export const getContentImageAssetUrl = (modulePath) => contentImageAssets[modulePath] || \'\'',
    'export const contentImageAssetPaths = Object.freeze(Object.keys(contentImageAssets))',
    '',
  ].join('\n')
}

const writeIfChanged = (file, content) => {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content, 'utf8')
  return true
}

const markdownFiles = await globby('**/*.md', {
  cwd: contentDir,
  absolute: true,
  onlyFiles: true,
})
const allImageFiles = await globby('**/*.{avif,gif,jpeg,jpg,png,svg,webp}', {
  cwd: contentDir,
  absolute: true,
  onlyFiles: true,
})

const referencedAssets = new Set()
for (const markdownFile of markdownFiles) {
  const content = fs.readFileSync(markdownFile, 'utf8')
  for (const match of content.matchAll(/!\[[^\]]*]\(([^)\n]+)\)/g)) {
    const assetFile = resolveReferencedAsset(markdownFile, match[1])
    if (!assetFile) continue
    if (!fs.existsSync(assetFile)) {
      throw new TypeError(`Referenced content image does not exist: ${toPosix(path.relative(root, assetFile))}`)
    }
    referencedAssets.add(assetFile)
  }
}

const entries = [...referencedAssets]
  .sort((a, b) => toPosix(a).localeCompare(toPosix(b)))
  .map((assetFile) => ({
    moduleKey: moduleKeyForAsset(assetFile),
    importPath: importPathForAsset(assetFile),
  }))

const unusedImageFiles = allImageFiles
  .filter((assetFile) => !referencedAssets.has(assetFile))
  .map((assetFile) => toPosix(path.relative(root, assetFile)))
  .sort()

const changed = writeIfChanged(outputFile, renderOutput(entries))
console.log(
  `[content-image-assets] ${changed ? 'Generated' : 'Verified'} ${toPosix(path.relative(root, outputFile))} with ${entries.length} referenced images.`,
)
if (unusedImageFiles.length) {
  console.log(`[content-image-assets] Unreferenced content images are excluded: ${unusedImageFiles.join(', ')}`)
}
